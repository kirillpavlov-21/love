/* Календарь поводов «Куда идём?»: праздники и события, к которым scripts/occasions.mjs собирает тематическую подборку
   (обычно за неделю до даты; убирает её на следующий день после окончания).
   Поле повода:
   ─ slug — латиницей, из него id подборки: c-o-<slug>-<год> (Москва) и spb-c-o-<slug>-<год> (Петербург);
   ─ title, emoji, lead — заголовок до 40 знаков и вступление своими словами до 300 знаков (общие или { msk, spb });
   ─ date(год) → 'YYYY-MM-DD' — день повода; days — сколько дней длится (1); before — за сколько дней показывать (7);
     approx — дата вычислена по правилу и может сдвинуться: её подтверждают в scripts/occasion-dates.json;
   ─ words — по каким словам искать посты каналов о поводе (scripts/occasions.mjs --posts);
   ─ cities — ['msk', 'spb'] по умолчанию; mode — для каких поводов на сайте, без поля — для всех;
   ─ pick — как отобрать пункты из каталога: hint (подсказки мест), cat (разделы мест), kind / text (рег. выражения по типу
     и описанию места), ev / evText (категории и рег. выражение по названию события в дни подборки), plan (теги и рег. выражение
     по названию готового плана). Сверху ставим пункты, которые ежедневная задача выбрала по постам каналов
     (~/.kuda/occasion-picks.json), потом события в дни повода, потом планы и места. */

const pad = n => String(n).padStart(2, '0');
const ymd = d => `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
const at = (y, m, d) => new Date(Date.UTC(y, m - 1, d));
export const addDays = (s, n) => { const d = new Date(Date.parse(s + 'T00:00:00Z') + n * 864e5); return ymd(d); };
const fixed = (m, d) => y => ymd(at(y, m, d));
/* n-я суббота месяца (n = 1…5) и первая суббота не раньше дня from */
const satFrom = (y, m, from) => { const d = at(y, m, from); d.setUTCDate(from + ((6 - d.getUTCDay() + 7) % 7)); return ymd(d); };
const nthSat = (y, m, n) => addDays(satFrom(y, m, 1), 7 * (n - 1));
/* Православная Пасха (алгоритм Гаусса для юлианского календаря + 13 дней — верно для 1900–2099) */
export function orthodoxEaster(y) {
  const a = y % 4, b = y % 7, c = y % 19, d = (19 * c + 15) % 30, e = (2 * a + 4 * b - d + 34) % 7;
  const month = Math.floor((d + e + 114) / 31), day = ((d + e + 114) % 31) + 1;
  return addDays(ymd(at(y, month, day)), 13);
}

