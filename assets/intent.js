  function parse(text, opt) {
    opt = opt || {};
    let t = norm(text);
    const o = {
      text: String(text || '').trim(), now: opt.now == null ? Date.now() : +opt.now, modes: {}, mode: null, group: false, city: null, first: false,
      bud: 0, free: false, premium: false, pair: / на двоих /.test(t),
      day: null, when: null, indoor: false, outdoor: false, near: false, station: null, okr: null, random: false, romantic: false, fresh: false,
      tags: new Set(), hints: new Set(), cats: new Set(), ev: new Set(), kinds: [], vibe: [], evChips: [], words: [], chips: [],
    };
    const cut = (r, fn) => { r.lastIndex = 0; t = t.replace(r, (...m) => { fn(m); return ' '; }).replace(/ {2,}/g, ' '); };
    // город раньше станций: станции ищем в городе запроса
    CITY_RULES.forEach(([r, c]) => cut(r, () => { if (!o.city) o.city = c; }));
    if (!o.city) { SPB_HINT.lastIndex = 0; if (SPB_HINT.test(t)) o.city = 'spb'; }
    const c = o.city || opt.city || (K() && typeof K().city === 'function' ? K().city() : 'msk');
    // станции и районы — раньше словаря: «Парк культуры», «Чистые пруды», «Спортивная» — места, а не настроение
    for (const x of stationRx(c)) { if (o.station) break; cut(x.rx, () => { if (!o.station) o.station = { name: x.s.name, lat: x.s.lat, lon: x.s.lon }; }); }
    for (const [id, r] of okrRx(c)) { if (o.okr) break; cut(r, () => { if (!o.okr) o.okr = id; }); }
    RULES.forEach(([r, fn]) => cut(r, m => fn(o, m)));
    // остальные слова — ищем по названиям и типам мест
    o.words = t.trim().split(' ').filter(w => w.length >= 3 && !STOP.has(w) && !/^\d+$/.test(w)).slice(0, 6);

    o.mode = o.modes.date >= 1 ? 'date' : o.modes.girls ? 'girls' : o.modes.guys || o.group ? 'guys' : o.modes.date ? 'date' : null;
    if (o.romantic && !o.mode) o.mode = 'date';
    if (o.first) o.hints.add('first');
    if (o.station) o.near = false;
    ['tags', 'hints', 'cats', 'ev'].forEach(k => { o[k] = Array.from(o[k]); });
    o.chips = chips(o);
    o.empty = !o.chips.length && !o.words.length;
    delete o.modes; delete o.evChips; delete o.vibe; delete o.pair;
    return o;
  }
  const MODE_CHIP = { date: ['💕', 'свидание'], guys: ['🍻', 'с друзьями'], girls: ['💅', 'с подругами'] };
  const WHEN_CHIP = { now: ['⏱️', 'прямо сейчас'], day: ['☀️', 'днём'], eve: ['🌆', 'вечером'], late: ['🌙', 'поздно'] };
  function chips(o) {
    const out = [], add = (k, e, t) => { if (!out.some(x => x.t === t)) out.push({ k, e, t }); };
    if (o.city) add('city', '📍', o.city === 'spb' ? 'Петербург' : 'Москва');
    if (o.mode) add('mode', ...MODE_CHIP[o.mode]);
    if (o.group && o.mode !== 'guys' && o.mode !== 'girls') add('group', '👥', 'компанией');
    if (o.first) add('first', '💘', 'первое свидание');
    if (o.day && o.when !== 'now') add('day', '📅', o.day === 'weekend' ? 'на выходных' : o.day === 'week' ? 'на неделе' : dayText(o.day, o.now));
    if (o.when) add('when', ...WHEN_CHIP[o.when]);
    if (o.free) add('free', '🆓', 'бесплатно');
    else if (o.bud) add('bud', '💸', o.bud === 1 ? `до 1${NB}500${NB}₽` : `до 3${NB}000${NB}₽`);
    if (o.premium) add('premium', '⭐', 'пошикарнее');
    if (o.indoor) add('indoor', '☔', 'под крышей');
    if (o.near) add('near', '📍', 'рядом со мной');
    if (o.station) add('station', 'Ⓜ️', o.station.name);
    if (o.okr) add('okr', '🗺️', okrName(o.city || (K() && typeof K().city === 'function' ? K().city() : 'msk'), o.okr));
    o.vibe.forEach(([, e, t]) => add('vibe', e, t));
    o.evChips.forEach(([, e, t]) => add('ev', e, t));
    if (o.random) add('random', '🎲', 'удиви меня');
    // стабильная сортировка: внутри одного k — в порядке, в каком нашли
    return out.sort((a, b) => ORDER.indexOf(a.k) - ORDER.indexOf(b.k));
  }
